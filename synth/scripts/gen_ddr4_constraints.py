#!/usr/bin/env python3
"""Generate the BCU-1525 DDR4 constraints from Xilinx's VCU1525 board file and the DRAM datasheet.

  python3 synth/scripts/gen_ddr4_constraints.py            write synth/constraints/BCU1525_DIMM[0-3].xdc
                                                           and synth/constraints/BLS4G4D240FSB.csv
  python3 synth/scripts/gen_ddr4_constraints.py --check    fail if the files on disk differ from the output

Inputs (both redistributable under Apache-2.0):
  synth/constraints/xilinx_vcu1525/part0_pins.xml   AMD/Xilinx VCU1525 board file (XilinxBoardStore
                                                    2024.2, vcu1525/1.3), names every FPGA pin of the
                                                    four DIMM slots, the 300 MHz refclks and PCIe
  the tables below                                  this script's own: which byte lanes the 64-bit
                                                    UDIMMs use, and JEDEC DDR4-2400 timings

The BCU-1525 is a VCU1525 derivative. The board file describes 72-bit (ECC) RDIMM channels: nine byte
lanes, each with two x4 strobes (dqs_t[2k], dqs_t[2k+1]). The BCU-1525's 4 GB UDIMMs are 64-bit x8,
so each channel uses eight of the nine lanes; on an x8 DIMM the second x4 strobe pin of a lane is that
byte's DM_n. Which lane carries the DIMM's (absent) check byte is a fact of the BCU-1525 board wiring,
not in the VCU1525 file: SKIP_LANE below, confirmed by DDR4 calibration on all four channels.
DQ bits keep the board file's order within each lane, and lanes keep ascending order (both are free
choices for the DDR4 controller: it calibrates every bit, and a byte's data only has to stay with its
strobe and DM).

I/O standards, termination and drive come from the DDR4 IP's own generated constraints; this file
sets only package pins, plus the board file's I/O attributes for the two non-memory pins it adds.
"""
import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CON = os.path.join(REPO, "synth/constraints")
PINS = os.path.join(CON, "xilinx_vcu1525/part0_pins.xml")

# board-file byte lane (0..8) with no DRAM behind it on the BCU-1525's 64-bit UDIMMs, per channel
SKIP_LANE = {0: 7, 1: 7, 2: 3, 3: 2}

HEADER = """\
# GENERATED by synth/scripts/gen_ddr4_constraints.py -- do not edit; edit the generator and rerun.
# Source: AMD/Xilinx VCU1525 board file synth/constraints/xilinx_vcu1525/part0_pins.xml (Apache-2.0),
#   channel c{d}, byte lanes {lanes} (lane {skip} has no DRAM on a 64-bit UDIMM).
# SQRL BCU-1525, DIMM slot {d}: DDR4 UDIMM 64-bit x8, single rank. Package pins only: the DDR4 IP's
#   generated XDC sets the I/O standards and terminations.
"""

DIMM0_EXTRA = """
# Bitstream compression
set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]

# PCIe x8: refclk and PERST# (board file pcie_mgt_clkp/n, pcie_perstn_rst)
set_property PACKAGE_PIN {clkp} [get_ports pcie_refclk_clk_p]
set_property PACKAGE_PIN {clkn} [get_ports pcie_refclk_clk_n]
set_property -dict {{PACKAGE_PIN {perst} IOSTANDARD {perst_ios}}} [get_ports pcie_perstn]
"""


def load_pins(path):
    pins = {}
    for m in re.finditer(r"<pin\b([^>]*)/?>", open(path).read()):
        a = dict(re.findall(r'(\w+)\s*="([^"]*)"', m.group(1)))
        if "name" in a and "loc" in a:
            pins[a["name"].strip()] = a
    return pins


def xdc(d, pins):
    lanes = [k for k in range(9) if k != SKIP_LANE[d]]
    p = f"C{d}_DDR4_0_"
    loc = lambda n: pins[f"c{d}_ddr4_{n}"]["loc"]
    out = [HEADER.format(d=d, lanes=",".join(map(str, lanes)), skip=SKIP_LANE[d])]
    if d == 0:
        out.append(DIMM0_EXTRA.format(clkp=pins["pcie_mgt_clkp"]["loc"], clkn=pins["pcie_mgt_clkn"]["loc"],
                                      perst=pins["pcie_perstn_rst"]["loc"],
                                      perst_ios=pins["pcie_perstn_rst"]["iostandard"]))

    def pp(pin, port):
        out.append(f"set_property PACKAGE_PIN {pin} [get_ports {{{port}}}]")

    out.append("\n# 300 MHz reference clock (board file default_300mhz_clk%d)" % d)
    pp(pins[f"default_300mhz_clk{d}_p"]["loc"], f"dimm{d}_refclk_clk_p")
    pp(pins[f"default_300mhz_clk{d}_n"]["loc"], f"dimm{d}_refclk_clk_n")
    rst = pins[f"c{d}_ddr4_reset_n"]
    out.append("\n# reset (board file I/O attributes)")
    out.append(f"set_property -dict {{PACKAGE_PIN {rst['loc']} IOSTANDARD {rst['iostandard']} "
               f"DRIVE {rst['drive']}}} [get_ports {p}reset_n]")
    out.append("\n# command / address")
    pp(loc("act_n"), p + "act_n")
    for i in range(17):
        pp(loc(f"adr{i}"), f"{p}adr[{i}]")
    for i in range(2):
        pp(loc(f"ba{i}"), f"{p}ba[{i}]")
    for i in range(2):
        pp(loc(f"bg{i}"), f"{p}bg[{i}]")
    for n, b in (("ck_t", "ck_t0"), ("ck_c", "ck_c0"), ("cke", "cke0"), ("cs_n", "cs0_n"), ("odt", "odt0")):
        pp(loc(b), f"{p}{n}[0]")
    out.append("\n# data: byte i = board lane lanes[i]; dq 8i+j = lane dq 8*lane+j, dqs = x4 strobe 2*lane,"
               " dm_n = x4 strobe 2*lane+1")
    for i, k in enumerate(lanes):
        for j in range(8):
            pp(loc(f"dq{8 * k + j}"), f"{p}dq[{8 * i + j}]")
        pp(loc(f"dqs_t{2 * k}"), f"{p}dqs_t[{i}]")
        pp(loc(f"dqs_c{2 * k}"), f"{p}dqs_c[{i}]")
        pp(loc(f"dqs_t{2 * k + 1}"), f"{p}dm_n[{i}]")
    return "\n".join(out) + "\n"


# Vivado DDR4 IP custom-part CSV (column set of the IP's "Custom Parts" format). One row: the -2400
# grade the shell uses. Crucial BLS4G4D240FSB: 4 GB single-rank UDIMM, eight 4Gb x8 DRAMs (1 KB page).
# Timings: JEDEC JESD79-4 DDR4-2400, 4Gb x8 (1 KB page); where noted, a more conservative value is used.
CSV_COLS = [
    ("Part type", "UDIMMs"), ("Part name", "BLS4G4D240FSB-2400"), ("Rank", "1"), ("StackHeight", "1"),
    ("CA Mirror", "0"), ("Data mask", "1"), ("Address width", "17"), ("Row width", "15"),
    ("Column width", "10"), ("Bank width", "2"), ("Bank group width", "2"), ("CS width", "1"),
    ("CKE width", "1"), ("ODT width", "1"), ("CK width", "1"), ("Memory speed grade", "2400"),
    ("Memory density", "4GB"), ("Component density", "4Gb"), ("Memory device width", "64"),
    ("Memory component width", "8"), ("Data bits per strobe", "8"), ("IO Voltages", "1.2V"),
    ("Data widths", "64"),
    ("Min period", "833"),            # tCK(avg) min, DDR4-2400, ps
    ("Max period", "1600"),           # slowest tCK the IP supports here, ps
    ("tCKE", "5000 ps"),              # max(3 nCK, 5 ns)
    ("tFAW", "21000 ps"),             # 1 KB page: max(20 nCK, 21 ns)
    ("tFAW_dlr", "0"),
    ("tMRD", "8 tck"),
    ("tRAS", "32000 ps"),             # 32 ns
    ("tRCD", "14160 ps"),             # 17 nCK at 0.833 ns; conservative vs DDR4-2400R 13.32 ns
    ("tREFI", "7800000 ps"),          # 7.8 us, 0..85 C
    ("tRFC", "350000 ps"),            # 8Gb value; conservative vs 4Gb 260 ns
    ("tRFC_dlr", "0"),
    ("tRP", "14160 ps"),              # as tRCD
    ("tRRD_S", "3300 ps"),            # 1 KB page: max(4 nCK, 3.3 ns)
    ("tRRD_L", "4900 ps"),            # 1 KB page: max(4 nCK, 4.9 ns)
    ("tRRD_dlr", "0"),
    ("tRTP", "7500 ps"),              # max(4 nCK, 7.5 ns)
    ("tWR", "15000 ps"),              # 15 ns
    ("tWTR_S", "2500 ps"),            # max(2 nCK, 2.5 ns)
    ("tWTR_L", "7500 ps"),            # max(4 nCK, 7.5 ns)
    ("tXPR", "360 ns"),               # tRFC + 10 ns
    ("tZQCS", "128 tck"), ("tZQINIT", "1024 tck"), ("tCCD_3ds", "0"),
    ("cas latency", "16"), ("cas write latency", "12"), ("burst length", "8"),
]


def csv():
    # no comment line: the DDR4 IP reads every line after the header as a part row
    return ",".join(c for c, _ in CSV_COLS) + "\n" + ",".join(v for _, v in CSV_COLS) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    pins = load_pins(PINS)
    files = {f"BCU1525_DIMM{d}.xdc": xdc(d, pins) for d in range(4)}
    files["BLS4G4D240FSB.csv"] = csv()
    bad = 0
    for name, text in files.items():
        path = os.path.join(CON, name)
        if args.check:
            same = os.path.exists(path) and open(path).read() == text
            print(f"{'ok  ' if same else 'DIFF'} {name}")
            bad += not same
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"wrote {name}")
    # every board pin used at most once across the four slots
    locs = re.findall(r"PACKAGE_PIN (\w+)", "".join(files[f"BCU1525_DIMM{d}.xdc"] for d in range(4)))
    dup = sorted({x for x in locs if locs.count(x) > 1})
    if dup:
        print("FATAL: pins assigned twice:", dup)
        return 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
