// opus_top_ipi: plain-Verilog IPI wrapper that puts the whole engine (rtl/opus_top.sv, through the
// array-free shim rtl/opus_top_flat.sv) into the Stage 3 FULL-DESIGN block design
// (synth/scripts/create_full.tcl, docs/ARCHITECTURE.md §5) as the module-reference cell opus_0.
//
// PROVENANCE: the X_INTERFACE attribute style and this header style are adapted from
// rtl/opus_shell_csr_ipi.v, whose port list came from fable5_llm (the user's own project), commit
