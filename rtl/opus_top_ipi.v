// opus_csr; adds the io-window AXI4 slave s_io and the four read-only AXI4 DDR4 masters m0..m3.
//
// Why a .v wrapper: Vivado IPI module references do not accept a SystemVerilog top file
// (filemgmt 56-195), and Verilog-2001 cannot connect opus_top's unpacked-array m_* ports, hence the
// opus_top_flat shim. Hierarchy: <cell>/inst/u_flat/u_top/{u_csr,u_eng,...}, so
// synth/constraints/fable5_cdc.xdc (false path to */u_csr/calib_meta_reg[*]/D) applies unchanged and
// synth/constraints/engine_slr_full.xdc finds the engine at */u_flat/u_top/u_eng.
//
// Clocks: aclk (XDMA axi_aclk, 250 MHz) clocks s_axil, s_io and the engine. m<i> runs on ui_clk<i>
// (DDR4 channel i's MIG ui_clk) with reset ui_rstn<i>; ddr_chan_rd does the CDC (xpm).
// Channel use: m0/m1/m3 BSK residue 0/1/2, m2 KSK load. Masters are read-only (no AW/W/B ports).
// The io window takes INCR bursts at full width only (rtl/io_win.sv): s_io declares no SIZE/BURST
// ports and SUPPORTS_NARROW_BURST 0, so the SmartConnect converts anything else.
//
// Generics as the stage-2 gate OOC engine (evidence/stage2/SUMMARY.md §3): RED_F=0 RED_M=1 RED_I=1
// PLOG=5 BSLOG=3 NC=918 KSL=184, twiddle ROMs from synth/roms/P5_mont and synth/roms/P5_table
// (generated by ref/tfhe_model dump_pipe; git-ignored, absolute paths read by $readmemh at synthesis).

