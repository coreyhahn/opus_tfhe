// Constant-geometry negacyclic NTT core for one 18-bit prime, N = 2048, T butterflies.
// Bit-exact target: ref/tfhe_model/src/ntt_q.rs (forward_stages / inverse_stages).
//
// A job is TWO polynomials (slots 0 and 1, e.g. the two digit polynomials of a CMux). The core
// runs their 11 stage passes interleaved (slot 0 stage s, slot 1 stage s, slot 0 stage s+1, ...)
// so one slot's butterfly pipeline drains while the other's issues.
//   DIR = 0 forward : natural order in,  NTT position order out (= bit-reversed evaluation order)
//   DIR = 1 inverse : position order in, natural order out, UNSCALED (x N)
//
// Memory. Positions are grouped in T-words (T consecutive coefficients); T-word t, 0 <= t < 2H,
// H = N/(2T), lives in bank t[0] ^ t[log2 H] at address t >> 1, so every compute access touches
// both banks once per cycle: forward reads (a, a+H), forward writes (2a, 2a+1), inverse reads
// (2a, 2a+1), inverse writes (a, a+H). Each (slot, bank) is ONE simple-dual-port RAM of depth 4H
// holding the 4 rotating job buffers (load / compute ping / compute pong / unload) in its address
// MSBs, so no data crossbar is needed. Compute owns a slot's read port while it issues that slot's
// pass and its write port while that pass's results land; loads drain from a FIFO into the write
// port, and unloads fill a FIFO from the read port, in the other cycles (the other slot's pass).
//
// Streams (M coefficients of each slot per beat, positions in increasing order, N/M beats/job):
//   in : the producer pulses in_job_start only in a cycle where in_job_ready = 1; that reserves a
//        load buffer in the same cycle. The N/M beats then follow with in_valid at any pace (the
//        first may be in the start cycle); the core accepts every valid beat of a reserved job.
//   out: the core starts a job (out_job_start pulse) only when out_job_ready = 1 and then emits
//        its N/M beats with out_valid, possibly with gaps; the consumer accepts every valid beat.
//        Chaining: next.in_job_start = out_job_start, out_job_ready = next.in_job_ready.
// Twiddles: ROM_FILE, 11*H lines, line s*H + a = the T lanes' stored constants (lane 0 in the
// low 18 bits), generated by the model (`dump_ntt`). Requires M <= T/2.
module ntt_cg #(
  parameter int    P         = 249857,
  parameter int    RED       = ntt_pkg::RED_MONT,
  parameter int    DIR       = 0,
  parameter int    T         = 8,
  parameter int    M         = 1,
  parameter string ROM_FILE  = "",
  parameter int    RAM_BLOCK = 1             // 1: block RAM, 0: distributed RAM
) (
  input  logic              clk,
  input  logic              rst,
  output logic              in_job_ready,
  input  logic              in_job_start,
  input  logic              in_valid,
  input  logic [M*18-1:0]   in_data0,
  input  logic [M*18-1:0]   in_data1,
  input  logic              out_job_ready,
  output logic              out_job_start,
  output logic              out_valid,
  output logic [M*18-1:0]   out_data0,
  output logic [M*18-1:0]   out_data1,
  output logic              busy
);
  localparam int N      = ntt_pkg::N;
  localparam int LOGN   = ntt_pkg::LOG_N;
  localparam int H      = N / (2 * T);
  localparam int HB     = $clog2(H);
  localparam int TW     = 18 * T;
  localparam int LB     = ntt_pkg::bfly_lat(RED);
  localparam int BPW    = T / M;             // beats per T-word
  localparam int LBPW   = $clog2(BPW);
  localparam int CB     = (BPW > 1) ? LBPW : 1;
  localparam int NB     = N / M;             // beats per job
  localparam int BB     = $clog2(NB) + 1;
  localparam int PASSES = 2 * LOGN;
  localparam int DRAIN  = LB + 3;            // last issue -> its writes visible to a new read
  localparam int RB     = $clog2(LOGN * H);
  localparam int AW     = 2 + HB;            // RAM address: {buffer, T-word >> 1}
  localparam int FDR    = H / BPW + LB / BPW + 6;
  localparam int FD     = (FDR <= 8) ? 8 : (1 << $clog2(FDR));
  localparam int FB     = $clog2(FD) + 1;

  initial begin
    if (T < 4 || T > 256 || (T & (T - 1)) != 0) $fatal(1, "ntt_cg: T must be a power of two in [4, 256]");
    if (M < 1 || BPW < 2 || (T % M) != 0 || (BPW & (BPW - 1)) != 0) $fatal(1, "ntt_cg: M must divide T/2");
  end

  function automatic logic bank_of(input logic [HB:0] t);
    return t[0] ^ t[HB];
  endfunction

  // ------------------------------------------------------------------ buffer bookkeeping
  typedef enum logic [2:0] {B_FREE, B_LOADING, B_LOADED, B_COMP, B_DONE, B_UNLOAD} bstate_e;
  bstate_e bst [4];

  logic [1:0] free_idx;
  logic       free_any, free_two;
  always_comb begin
    free_any = 1'b0;
    free_two = 1'b0;
    free_idx = '0;
    for (int i = 3; i >= 0; i--) begin
      if (bst[i] == B_FREE) begin
        free_two = free_any;
        free_any = 1'b1;
        free_idx = 2'(i);
      end
    end
  end
  function automatic logic [1:0] next_free_after(input logic [1:0] first);
    for (int i = 0; i < 4; i++) if (bst[i] == B_FREE && 2'(i) != first) return 2'(i);
    return first;
  endfunction

  // Jobs leave in arrival order: loaded and done buffers wait in FIFOs of buffer indices.
  logic [1:0] lq [4];
  logic [1:0] lq_rd, lq_wr;
  logic [2:0] lq_n;
  logic [1:0] dq [4];
  logic [1:0] dq_rd, dq_wr;
  logic [2:0] dq_n;
  wire        loaded_any = (lq_n != 0);
  wire  [1:0] loaded_buf = lq[lq_rd];
  wire        done_any   = (dq_n != 0);
  wire  [1:0] done_buf   = dq[dq_rd];

  // ------------------------------------------------------------------ RAMs: [slot][bank]
  logic          r_we [2][2];
  logic [AW-1:0] r_wa [2][2];
  logic [TW-1:0] r_wd [2][2];
  logic [AW-1:0] r_ra [2][2];
  logic [TW-1:0] r_rd [2][2];
  for (genvar q = 0; q < 2; q++) begin : g_q
    for (genvar k = 0; k < 2; k++) begin : g_k
      if (RAM_BLOCK != 0) begin : g_bram
        (* ram_style = "block" *) logic [TW-1:0] arr [4*H];
        always_ff @(posedge clk) begin
          if (r_we[q][k]) arr[r_wa[q][k]] <= r_wd[q][k];
          r_rd[q][k] <= arr[r_ra[q][k]];
        end
      end else begin : g_lram
        (* ram_style = "distributed" *) logic [TW-1:0] arr [4*H];
        always_ff @(posedge clk) begin
          if (r_we[q][k]) arr[r_wa[q][k]] <= r_wd[q][k];
          r_rd[q][k] <= arr[r_ra[q][k]];
        end
      end
    end
  end

  logic [TW-1:0] rom [LOGN * H];
  initial if (ROM_FILE != "") $readmemh(ROM_FILE, rom);

  // ------------------------------------------------------------------ compute engine
  logic          c_busy, c_issuing, c_finish_pending;
  logic [1:0]    c_in, c_oth;
  logic [4:0]    c_pass;
  logic [HB-1:0] c_a;
  logic [7:0]    drain [2];
  logic [7:0]    c_finish_cnt;
  logic          c_start;

  wire       cq    = c_pass[0];
  wire [3:0] cs    = c_pass[4:1];
  wire [1:0] c_src = cs[0] ? c_oth : c_in;
  wire [1:0] c_dst = cs[0] ? c_in  : c_oth;
  wire       c_rd  = c_issuing && c_busy && !c_finish_pending;   // a compute read this cycle

  logic [HB-1:0] cr_addr [2];
  always_comb begin
    for (int k = 0; k < 2; k++) begin
      if (DIR == 0) cr_addr[k] = (1'(k) == c_a[0]) ? (c_a >> 1) : HB'((c_a >> 1) + HB'(H / 2));
      else          cr_addr[k] = c_a;
    end
  end

  // md[i] is valid in cycle issue+1+i: md[0] is aligned with the read data and the twiddle,
  // md[LB] with the butterfly outputs (written at the end of that cycle)
  localparam int MD = LB;
  logic          md_v   [MD+1];
  logic          md_q   [MD+1];
  logic [1:0]    md_dst [MD+1];
  logic [HB-1:0] md_a   [MD+1];

  logic [TW-1:0] rom_q;
  always_ff @(posedge clk) rom_q <= rom[RB'(cs) * RB'(H) + RB'(c_a)];

  logic [TW-1:0] w0, w1;
  logic [17:0]   bu [T], bv [T], ba [T], bb [T], bw [T];
  always_comb begin
    logic first_bank;
    first_bank = (DIR == 0) ? md_a[0][0] : md_a[0][HB-1];
    w0 = r_rd[md_q[0]][first_bank];
    w1 = r_rd[md_q[0]][~first_bank];
    for (int l = 0; l < T; l++) begin
      bw[l] = rom_q[18*l +: 18];
      if (DIR == 0) begin
        bu[l] = w0[18*l +: 18];
        bv[l] = w1[18*l +: 18];
      end else if (l < T / 2) begin
        bu[l] = w0[18*(2*l) +: 18];
        bv[l] = w0[18*(2*l+1) +: 18];
      end else begin
        bu[l] = w1[18*(2*l-T) +: 18];
        bv[l] = w1[18*(2*l+1-T) +: 18];
      end
    end
  end

  for (genvar l = 0; l < T; l++) begin : g_bf
    bfly #(.P(P), .RED(RED), .DIR(DIR)) u_bf (
      .clk(clk), .u(bu[l]), .v(bv[l]), .wc(bw[l]), .a(ba[l]), .b(bb[l]));
  end

  // compute write: two T-words per cycle, one per bank
  logic          cw_we, cw_q;
  logic [1:0]    cw_b;
  logic [HB-1:0] cw_addr [2];
  logic [TW-1:0] cw_data [2];
  always_comb begin
    logic [HB-1:0] a;
    logic [TW-1:0] x0, x1;   // fwd: T-words 2a, 2a+1; inv: T-words a, a+H
    logic          b0;       // bank of x0
    a = md_a[MD];
    x0 = '0;
    x1 = '0;
    for (int l = 0; l < T; l++) begin
      if (DIR == 0) begin
        if (l < T / 2) begin
          x0[18*(2*l) +: 18]   = ba[l];
          x0[18*(2*l+1) +: 18] = bb[l];
        end else begin
          x1[18*(2*l-T) +: 18]   = ba[l];
          x1[18*(2*l+1-T) +: 18] = bb[l];
        end
      end else begin
        x0[18*l +: 18] = ba[l];
        x1[18*l +: 18] = bb[l];
      end
    end
    cw_we = md_v[MD];
    cw_q  = md_q[MD];
    cw_b  = md_dst[MD];
    if (DIR == 0) begin
      b0 = a[HB-1];                       // bank(2a); both words at address a
      cw_addr[0] = a;
      cw_addr[1] = a;
    end else begin
      b0 = a[0];                          // bank(a): x0 at a>>1, x1 (T-word a+H) at (a>>1)+H/2
      cw_addr[0] = b0 ? HB'((a >> 1) + HB'(H / 2)) : (a >> 1);
      cw_addr[1] = b0 ? (a >> 1) : HB'((a >> 1) + HB'(H / 2));
    end
    cw_data[0] = b0 ? x1 : x0;
    cw_data[1] = b0 ? x0 : x1;
  end

  // ------------------------------------------------------------------ load engine
  logic          ld_busy, ld_claim, ld_take;
  logic [1:0]    ld_buf, ld_buf_eff;
  logic [BB-1:0] ld_beat;
  logic [HB+1:0] ld_wcnt [2];             // T-words of the job written to RAM, per slot
  // the top M lanes of the accumulators are never read: the last beat of a T-word goes straight
  // into the FIFO with the lower lanes
  /* verilator lint_off UNUSEDSIGNAL */
  logic [TW-1:0] ld_acc [2];
  /* verilator lint_on UNUSEDSIGNAL */
  wire  [HB:0]   ld_t = (HB+1)'(ld_beat >> LBPW);
  wire  [CB-1:0] ld_c = CB'(ld_beat);
  wire           ld_accepting = ld_busy && (ld_beat != BB'(NB));

  logic             lf_push;
  logic             lf_pop [2];
  logic [HB+TW:0]   lf_head [2];          // {t, word}
  logic [FB-1:0]    lf_cnt  [2];
  assign lf_push = ld_take && (ld_c == CB'(BPW - 1));
  for (genvar q = 0; q < 2; q++) begin : g_lf
    sfifo #(.W(HB + 1 + TW), .DEPTH(FD)) u_lf (
      .clk(clk), .rst(rst), .push(lf_push),
      .din({ld_t, (q == 0) ? in_data0 : in_data1, ld_acc[q][TW-M*18-1:0]}),
      .pop(lf_pop[q]), .head(lf_head[q]), .count(lf_cnt[q]));
  end

  // ------------------------------------------------------------------ unload engine
  logic          ul_busy, ul_start, ul_rd_done;
  logic [1:0]    ul_buf;
  logic [HB+1:0] ul_rt [2];               // next T-word to read, per slot
  logic          ul_iss [2], ul_rv [2];
  logic          ul_rbank [2];
  logic [BB-1:0] ul_obeat;
  logic [CB-1:0] ul_oc;
  logic          of_pop;
  logic [TW-1:0] of_head [2];
  logic [FB-1:0] of_cnt  [2];
  for (genvar q = 0; q < 2; q++) begin : g_of
    sfifo #(.W(TW), .DEPTH(FD)) u_of (
      .clk(clk), .rst(rst), .push(ul_rv[q]), .din(r_rd[q][ul_rbank[q]]),
      .pop(of_pop), .head(of_head[q]), .count(of_cnt[q]));
  end

  // ------------------------------------------------------------------ RAM port arbitration
  always_comb begin
    for (int q = 0; q < 2; q++) begin
      logic [HB-1:0] ua;
      // unload read: one T-word of slot q when compute does not own the read port
      ua = ul_rt[q][HB:1];
      ul_iss[q] = ul_busy && (ul_rt[q] != (HB+2)'(2 * H)) && !(c_rd && cq == 1'(q))
                  && ({1'b0, of_cnt[q]} + (FB+1)'(ul_rv[q]) < (FB+1)'(FD - 1));
      // load drain: when compute does not write slot q this cycle
      lf_pop[q] = (lf_cnt[q] != 0) && !(cw_we && cw_q == 1'(q));
      for (int k = 0; k < 2; k++) begin
        if (c_rd && cq == 1'(q)) r_ra[q][k] = {c_src, cr_addr[k]};
        else                     r_ra[q][k] = {ul_buf, ua};
        if (cw_we && cw_q == 1'(q)) begin
          r_we[q][k] = 1'b1;
          r_wa[q][k] = {cw_b, cw_addr[k]};
          r_wd[q][k] = cw_data[k];
        end else begin
          r_we[q][k] = lf_pop[q] && (1'(k) == bank_of(lf_head[q][HB+TW:TW]));
          r_wa[q][k] = {ld_buf, lf_head[q][HB+TW:TW+1]};
          r_wd[q][k] = lf_head[q][TW-1:0];
        end
      end
    end
  end

  // ------------------------------------------------------------------ control
  assign c_start       = !c_busy && loaded_any && free_any;
  assign in_job_ready  = !ld_busy && free_any && !(c_start && !free_two);
  assign ld_claim      = in_job_start && in_job_ready;
  assign ld_take       = in_valid && (ld_accepting || ld_claim);
  assign ld_buf_eff    = ld_busy ? ld_buf : (c_start ? next_free_after(free_idx) : free_idx);
  assign ul_start      = !ul_busy && done_any && out_job_ready;
  assign out_job_start = ul_start;
  assign of_pop        = ul_busy && (of_cnt[0] != 0) && (of_cnt[1] != 0) && (ul_oc == CB'(BPW - 1));
  assign busy          = ld_busy || c_busy || ul_busy || done_any || loaded_any;

  wire ld_last = ld_busy && (ld_wcnt[0] == (HB+2)'(2 * H)) && (ld_wcnt[1] == (HB+2)'(2 * H));

  always_ff @(posedge clk) begin
    if (rst) begin
      for (int i = 0; i < 4; i++) bst[i] <= B_FREE;
      ld_busy <= 1'b0; ld_beat <= '0; ld_wcnt[0] <= '0; ld_wcnt[1] <= '0;
      c_busy <= 1'b0; c_issuing <= 1'b0; c_pass <= '0; c_a <= '0;
      drain[0] <= '0; drain[1] <= '0;
      c_finish_pending <= 1'b0; c_finish_cnt <= '0;
      ul_busy <= 1'b0; ul_rd_done <= 1'b0; ul_obeat <= '0; ul_oc <= '0;
      ul_rt[0] <= '0; ul_rt[1] <= '0; ul_rv[0] <= 1'b0; ul_rv[1] <= 1'b0;
      out_valid <= 1'b0;
      lq_rd <= '0; lq_wr <= '0; lq_n <= '0;
      dq_rd <= '0; dq_wr <= '0; dq_n <= '0;
      for (int i = 0; i <= MD; i++) md_v[i] <= 1'b0;
    end else begin
      // ---- load: the claim reserves a buffer whether or not a beat comes with it
      if (ld_claim) begin
        ld_busy <= 1'b1;
        ld_buf  <= ld_buf_eff;
        bst[ld_buf_eff] <= B_LOADING;
        ld_beat <= '0;
      end
      if (ld_take) begin
        ld_acc[0][ld_c*M*18 +: M*18] <= in_data0;
        ld_acc[1][ld_c*M*18 +: M*18] <= in_data1;
        ld_beat <= (ld_claim ? '0 : ld_beat) + 1'b1;
      end
      for (int q = 0; q < 2; q++) if (lf_pop[q]) ld_wcnt[q] <= ld_wcnt[q] + 1'b1;
      if (ld_last) begin
        ld_busy <= 1'b0;
        ld_beat <= '0;
        ld_wcnt[0] <= '0;
        ld_wcnt[1] <= '0;
        bst[ld_buf] <= B_LOADED;
        lq[lq_wr] <= ld_buf;
        lq_wr <= lq_wr + 1'b1;
      end

      // ---- compute
      for (int q = 0; q < 2; q++) if (drain[q] != 0) drain[q] <= drain[q] - 1'b1;
      if (c_start) begin
        c_busy <= 1'b1;
        c_in   <= loaded_buf;
        c_oth  <= free_idx;
        bst[loaded_buf] <= B_COMP;
        bst[free_idx]   <= B_COMP;
        c_pass <= '0;
        c_a    <= '0;
        c_issuing <= 1'b0;
      end else if (c_busy && !c_finish_pending) begin
        if (!c_issuing) begin
          if (drain[cq] == 0) c_issuing <= 1'b1;
        end else if (c_a == HB'(H - 1)) begin
          c_a <= '0;
          drain[cq] <= 8'(DRAIN);
          if (c_pass == 5'(PASSES - 1)) begin
            c_issuing <= 1'b0;
            c_finish_pending <= 1'b1;
            c_finish_cnt <= 8'(DRAIN);
          end else begin
            c_pass <= c_pass + 1'b1;
            c_issuing <= (drain[~cq] == 0);
          end
        end else begin
          c_a <= c_a + 1'b1;
        end
      end
      if (c_finish_pending) begin
        if (c_finish_cnt == 0) begin
          c_finish_pending <= 1'b0;
          c_busy <= 1'b0;
          bst[c_in]  <= B_FREE;
          bst[c_oth] <= B_DONE;   // 11 stages (odd): the result is in the "other" buffer
          dq[dq_wr] <= c_oth;
          dq_wr <= dq_wr + 1'b1;
        end else begin
          c_finish_cnt <= c_finish_cnt - 1'b1;
        end
      end

      // queue occupancy
      lq_n <= lq_n + 3'(ld_last) - 3'(c_start);
      if (c_start) lq_rd <= lq_rd + 1'b1;
      dq_n <= dq_n + 3'(c_finish_pending && c_finish_cnt == 0) - 3'(ul_start);
      if (ul_start) dq_rd <= dq_rd + 1'b1;

      // metadata pipeline
      md_v[0]   <= c_rd;
      md_q[0]   <= cq;
      md_dst[0] <= c_dst;
      md_a[0]   <= c_a;
      for (int i = 1; i <= MD; i++) begin
        md_v[i] <= md_v[i-1]; md_q[i] <= md_q[i-1]; md_dst[i] <= md_dst[i-1]; md_a[i] <= md_a[i-1];
      end

      // ---- unload
      for (int q = 0; q < 2; q++) begin
        ul_rv[q]    <= ul_iss[q];
        ul_rbank[q] <= bank_of(ul_rt[q][HB:0]);
        if (ul_iss[q]) ul_rt[q] <= ul_rt[q] + 1'b1;
      end
      if (ul_start) begin
        ul_busy <= 1'b1;
        ul_buf  <= done_buf;
        bst[done_buf] <= B_UNLOAD;
        ul_rt[0] <= '0;
        ul_rt[1] <= '0;
        ul_obeat <= '0;
        ul_oc <= '0;
        ul_rd_done <= 1'b0;
      end else if (ul_busy) begin
        // the buffer is free once every T-word has been read into the output FIFOs
        if (!ul_rd_done && ul_rt[0] == (HB+2)'(2 * H) && ul_rt[1] == (HB+2)'(2 * H) && !ul_rv[0] && !ul_rv[1]) begin
          ul_rd_done <= 1'b1;
          bst[ul_buf] <= B_FREE;
        end
      end
      out_valid <= 1'b0;
      if (ul_busy && of_cnt[0] != 0 && of_cnt[1] != 0) begin
        out_valid <= 1'b1;
        out_data0 <= of_head[0][ul_oc*M*18 +: M*18];
        out_data1 <= of_head[1][ul_oc*M*18 +: M*18];
        ul_oc <= ul_oc + 1'b1;
        if (ul_obeat == BB'(NB - 1)) ul_busy <= 1'b0;
        ul_obeat <= ul_obeat + 1'b1;
      end
    end
  end

  // synthesis translate_off
  // lifecycle trace, enabled with +ntt_trace (simulation only)
  bit trace_on;
  longint tcyc = 0;
  initial trace_on = $test$plusargs("ntt_trace");
  always @(posedge clk) if (!rst && trace_on) begin
    tcyc <= tcyc + 1;
    if (ld_claim) $display("[%m] %0d claim buf %0d", tcyc, ld_buf_eff);
    if (ld_last) $display("[%m] %0d load done buf %0d", tcyc, ld_buf);
    if (c_start) $display("[%m] %0d compute start in %0d oth %0d", tcyc, loaded_buf, free_idx);
    if (c_finish_pending && c_finish_cnt == 0) $display("[%m] %0d compute done -> buf %0d", tcyc, c_oth);
    if (ul_start) $display("[%m] %0d unload start buf %0d", tcyc, done_buf);
  end
  // synthesis translate_on
endmodule
